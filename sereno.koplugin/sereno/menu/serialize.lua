--[[--
Writes a menu order table as a Lua source file that KOReader's MenuSorter
can dofile(). Output is deterministic (sorted keys) so we can skip writing
when nothing changed and spare the e-reader's flash storage.
]]

local Serialize = {}

Serialize.HEADER = "-- generated by sereno.koplugin: do not edit, your changes would be overwritten.\n"
    .. "-- To customise menus use Settings > Sereno > Customize levels, or turn tiered menus off to restore your own file.\n"

local function quote(s)
    return string.format("%q", s)
end

local function key(k)
    if type(k) == "string" and k:match("^[%a_][%w_]*$") then
        return k
    end
    return "[" .. quote(k) .. "]"
end

function Serialize.order(order)
    local keys = {}
    for k in pairs(order) do keys[#keys + 1] = k end
    table.sort(keys, function(a, b) return tostring(a) < tostring(b) end)

    local lines = { Serialize.HEADER, "return {" }
    for _, k in ipairs(keys) do
        local list = order[k]
        local items = {}
        for i, v in ipairs(list) do items[i] = "        " .. quote(v) .. "," end
        if #items == 0 then
            lines[#lines + 1] = "    " .. key(k) .. " = {},"
        else
            lines[#lines + 1] = "    " .. key(k) .. " = {"
            for _, item in ipairs(items) do lines[#lines + 1] = item end
            lines[#lines + 1] = "    },"
        end
    end
    lines[#lines + 1] = "}"
    return table.concat(lines, "\n") .. "\n"
end

function Serialize.isOurs(content)
    return type(content) == "string" and content:sub(1, #Serialize.HEADER) == Serialize.HEADER
end

return Serialize
